#!/usr/bin/env bash
# Extracts the internal layout constants used by src/sdk_bridge.cpp from the
# shipped SDK binary. The library keeps its handle array in a local (non
# exported) BSS symbol, so the offset has to be recovered from the symbol table.
#
# Usage: extract_sdk_layout.sh <path-to-.so> [output-header]
set -euo pipefail

SO="${1:-third_party/hps_sdk/lib/libHPS3DSDK64_1-8-6.so}"
OUT="${2:-include/hps3d160_max/generated/sdk_layout.h}"

if [[ ! -f "$SO" ]]; then
  echo "sdk library not found: $SO" >&2
  exit 1
fi

if ! command -v nm >/dev/null 2>&1; then
  echo "nm not available, keeping built-in defaults" >&2
  exit 0
fi

OFFSET="$(nm --defined-only "$SO" 2>/dev/null | awk '$3=="g_BaseHandle"{print $1; exit}')"
if [[ -z "$OFFSET" ]]; then
  echo "symbol g_BaseHandle not found in $SO (stripped?), keeping built-in defaults" >&2
  exit 0
fi

mkdir -p "$(dirname "$OUT")"
cat > "$OUT" <<EOF
// Auto-generated by scripts/extract_sdk_layout.sh - do not edit.
#pragma once
#define HPS_SDK_BASE_HANDLE_OFFSET 0x${OFFSET^^}ULL
#define HPS_SDK_HANDLE_STRIDE 104ULL
EOF

echo "wrote $OUT (g_BaseHandle @ 0x${OFFSET^^})"
